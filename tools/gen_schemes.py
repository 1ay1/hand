#!/usr/bin/env python3
"""Generate hand's colour-scheme presets from mbadolato/iTerm2-Color-Schemes.

    git clone --depth 1 --filter=blob:none --sparse \\
        https://github.com/mbadolato/iTerm2-Color-Schemes /tmp/itc
    (cd /tmp/itc && git sparse-checkout set ghostty)
    tools/gen_schemes.py /tmp/itc/ghostty > include/hand/schemes_gen.hpp

The same source maya compiles its schemes from, but hand keeps the WHOLE
palette -- a terminal needs all sixteen slots, not a semantic projection of
them. Each preset is: name, background, foreground, cursor, selection, the
sixteen ANSI colours, and the accent hand derives (the most chromatic of the
palette's blues/magentas/cyans that reads on the background), so the chrome
of every preset is coloured BY the preset.

Emitted sorted by name (case-folded) so lookup by name is a binary search.
"""

import colorsys
import re
import sys
from pathlib import Path

def hexval(s: str) -> int:
    s = s.strip().lstrip("#")
    if len(s) == 3:
        s = "".join(ch * 2 for ch in s)
    return int(s[:6], 16)


def parse(text: str) -> dict:
    p = {"palette": [None] * 16}
    for line in text.splitlines():
        m = re.match(r"\s*palette\s*=\s*(\d+)\s*=\s*(#?[0-9a-fA-F]{3,8})", line)
        if m:
            i = int(m.group(1))
            if 0 <= i < 16:
                p["palette"][i] = hexval(m.group(2))
            continue
        m = re.match(r"\s*([a-z-]+)\s*=\s*(#?[0-9a-fA-F]{3,8})\s*$", line)
        if m:
            p[m.group(1)] = hexval(m.group(2))
    return p


def rgb(c: int):
    return ((c >> 16) & 255) / 255.0, ((c >> 8) & 255) / 255.0, (c & 255) / 255.0


def lum(c: int) -> float:
    def ch(v):
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(c)
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a: int, b: int) -> float:
    la, lb = lum(a), lum(b)
    hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)


def chroma(c: int) -> float:
    r, g, b = rgb(c)
    return colorsys.rgb_to_hsv(r, g, b)[1] * max(r, g, b)


def accent_of(p: dict) -> int:
    bg = p["background"]
    pal = p["palette"]
    candidates = [pal[i] for i in (12, 4, 13, 5, 14, 6, 10, 2) if pal[i] is not None]
    cur = p.get("cursor-color")
    if cur is not None and chroma(cur) > 0.25:
        candidates.insert(0, cur)
    readable = [c for c in candidates if contrast(c, bg) >= 3.0]
    pool = readable or candidates or [p["foreground"]]
    return max(pool, key=chroma) if readable else pool[0]


def main() -> int:
    src = Path(sys.argv[1])
    rows = []
    for f in sorted(src.iterdir(), key=lambda x: x.name.casefold()):
        if not f.is_file():
            continue
        p = parse(f.read_text(errors="replace"))
        if "background" not in p or "foreground" not in p or any(v is None for v in p["palette"]):
            continue
        name = f.name
        bg, fg = p["background"], p["foreground"]
        cursor = p.get("cursor-color", fg)
        sel = p.get("selection-background", None)
        if sel is None or contrast(sel, bg) < 1.05 or contrast(sel, fg) < 2.5:
            # derive: 30% of the accent over the paper
            a = accent_of(p)
            sel = 0
            for sh in (16, 8, 0):
                x = (bg >> sh) & 255
                y = (a >> sh) & 255
                sel |= int(x + (y - x) * 0.3) << sh
        light = lum(bg) > 0.35
        rows.append((name, light, bg, fg, cursor, sel, p["palette"], accent_of(p)))

    out = []
    w = out.append
    w("#pragma once")
    w("// hand: colour-scheme presets.")
    w("//")
    w("// GENERATED by tools/gen_schemes.py from mbadolato/iTerm2-Color-Schemes")
    w("// (ghostty format). Do not edit by hand; re-run the generator.")
    w("//")
    w(f"// {len(rows)} presets, sorted by case-folded name.")
    w("")
    w("#include <array>")
    w("#include <cstdint>")
    w("#include <string_view>")
    w("")
    w("namespace hand::presets {")
    w("")
    w("struct Preset {")
    w("    std::string_view name;")
    w("    bool             light;")
    w("    std::uint32_t    paper, ink, cursor, selection, accent;")
    w("    std::array<std::uint32_t, 16> ansi;")
    w("};")
    w("")
    w(f"inline constexpr std::array<Preset, {len(rows)}> all{{{{")
    for name, light, bg, fg, cur, sel, pal, acc in rows:
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        ansi = ", ".join(f"0x{c:06X}" for c in pal)
        w(f'    {{"{esc}", {"true" if light else "false"}, 0x{bg:06X}, 0x{fg:06X}, 0x{cur:06X}, 0x{sel:06X}, 0x{acc:06X},')
        w(f"     {{{ansi}}}}},")
    w("}};")
    w("")
    w("}  // namespace hand::presets")
    sys.stdout.write("\n".join(out) + "\n")
    print(f"{len(rows)} presets", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
